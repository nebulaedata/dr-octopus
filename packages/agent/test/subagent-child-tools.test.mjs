test('every child loader rejects stale authority and refreshes admission without parent tool_call', async () => {
  const parent = harness();
  const service = fullPermissions();
  const entries = [];
  let branch = [];
  const ctx = {
    cwd: process.cwd(),
    isProjectTrusted: () => false,
    sessionManager: {
      getBranch: () => branch,
      getSessionId: () => 'admission',
      getSessionFile: () => undefined,
    },
  };
  createSubagentBridgeExtension(
    { agentDir: tmpdir(), workspaceId: 'w', permissionService: service },
    {
      loadRequiredChildApi: async () => ({ registerRequiredChildExtensions: () => ({ dispose() {} }) }),
      ensureExplorerAgent: async () => {},
      ensureChildEntry: async (scope, admission) => {
        entries.push({ scope, admission });
        return '/fixture.mjs';
      },
    }
  )(parent.pi);
  await parent.events.get('session_start')({}, ctx);
  try {
    const initial = entries.at(-1).admission;
    await verifyChildAdmission(initial);
    // Slash commands and the structured API do not emit parent tool_call.
    service.setMode('ask');
    await assert.rejects(verifyChildAdmission(initial), /CHILD_SCOPE_STALE/);
    assert.equal(entries.at(-1).scope.permissions.mode, 'ask');
    assert.equal(entries.at(-1).scope.tools.includes('ocr_image'), false);
    const current = entries.at(-1).admission;
    await verifyChildAdmission(current);
    branch = [{ type: 'custom', customType: 'octopus-knowledge-mode', data: {} }];
    await assert.rejects(verifyChildAdmission(current), /CHILD_SCOPE_STALE/);
    branch = [];
    await verifyChildAdmission(current); // Recovery does not require a parent tool_call.
    await assert.rejects(verifyChildAdmission({ ...current, token: '0'.repeat(64) }), /CHILD_SCOPE_STALE/);
    parent.active.splice(0, parent.active.length);
    await assert.rejects(verifyChildAdmission(current), /CHILD_SCOPE_STALE/);
    assert.deepEqual(entries.at(-1).scope.tools, []);
  } finally {
    await parent.events.get('session_shutdown')();
  }
  await assert.rejects(verifyChildAdmission(entries.at(-1).admission), /CHILD_ADMISSION_UNAVAILABLE/);
});
