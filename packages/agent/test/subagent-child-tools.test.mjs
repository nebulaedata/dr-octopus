test('memory child reads real SQLite, honors off policy and never initializes missing storage', async () => {
  const root = await mkdtemp(join(tmpdir(), 'octopus-child-memory-'));
  const child = harness();
  createMemoryChildExtension({ dataRoot: root })(child.pi);
  const recall = (input = { mode: 'page' }) => child.tools.get('memory_recall').execute('id', input);
  assert.deepEqual((await recall()).details.items, []);
  assert.deepEqual(await readdir(root), []);
  const writer = createMemoryService({ dataRoot: root });
  const receipt = await writer.remember({
    requestId: 'one',
    canonicalKey: 'child.test',
    topic: 'Test',
    type: 'preference',
    indexText: 'Child fact',
    bodyMd: 'Readonly child fact',
    action: 'create',
    sources: [{ sessionId: 'parent', entryId: 'one', evidence: 'Readonly child fact' }],
  });
  assert.equal((await recall()).details.items.length, 1);
  const read = await child.tools.get('memory_read').execute('id', { refs: [receipt.ref] });
  assert.match(JSON.stringify(read.details), /Readonly child fact/);
  const status = await writer.getStatus();
  await writer.setPolicy({ requestId: 'off', mode: 'off', expectedRevision: status.revision });
  await assert.rejects(recall(), { code: 'READ_ONLY' });
  await child.events.get('session_shutdown')();
  await child.events.get('session_shutdown')();
  await writer.dispose();
});

test('delegated execution checks actual paths and never promotes ask or deny to allow', () => {
  for (const [mode, policy, input, error] of [
    ['full', 'deny', { texts: ['one'] }, /CHILD_PERMISSION_DENIED/],
    ['full', 'ask', { texts: ['one'] }, /CHILD_PERMISSION_REQUIRED/],
    ['ask', undefined, { texts: ['one'] }, /CHILD_PERMISSION_REQUIRED/],
    ['full', 'allow', { path: '.ssh/key.png' }, /CHILD_PERMISSION_DENIED/],
  ]) {
    const child = harness();
    const permissions = permissionSnapshot(mode);
    const name = input.path ? 'ocr_image' : 'embed_text';
    if (policy) permissions.configuration.policy.tools[name] = policy;
    createScopedChildExtension({
      agentDir: tmpdir(),
      workspaceId: 'w',
      collectionIds: [],
      tools: [...CHILD_TOOLS],
      permissions,
    })(child.pi);
    assert.throws(
      () => child.tools.get(name).execute('id', input, undefined, undefined, { cwd: process.cwd() }),
      error
    );
  }
});

test('diagnostics explain admission and child allowlists without creating resources', () => {
  const permissions = permissionSnapshot();
  permissions.configuration.policy.tools.ocr_image = 'deny';
  permissions.configuration.policy.tools.embed_text = 'ask';
  const input = {
    permissions,
    cwd: process.cwd(),
    knowledgeEnabled: false,
    activeTools: CHILD_TOOLS.filter((name) => name !== 'memory_read'),
    registeredTools: CHILD_TOOLS.filter((name) => name !== 'memory_recall'),
  };
  const rows = inspectDelegatedTools(input, [...CHILD_TOOLS, 'made_up_tool']);
  const reason = (name) => rows.find((row) => row.name === name).reason;
  assert.equal(reason('ocr_image'), 'permission_deny');
  assert.equal(reason('embed_text'), 'permission_ask');
  assert.equal(reason('rerank_documents'), 'eligible');
  assert.equal(reason('knowledge_search'), 'knowledge_mode_disabled');
  assert.equal(reason('memory_read'), 'parent_tool_inactive');
  assert.equal(reason('memory_recall'), 'parent_tool_missing');
  assert.equal(reason('made_up_tool'), 'not_delegatable');
  assert.equal(
    inspectDelegatedTools({ ...input, childTools: [] }, ['rerank_documents'])[0].reason,
    'child_allowlist_excluded'
  );
});

