test('second identity registration failure rolls back the first and can recover', async () => {
  const { pi, events } = harness();
  const registered = new Set();
  let fail = true;
  createSubagentBridgeExtension(
    { agentDir: '/agent', workspaceId: 'w', permissionService: fullPermissions() },
    {
      loadRequiredChildApi: async () => ({
        registerRequiredChildExtensions: ({ sessionId }) => {
          if (sessionId === 'uuid' && fail) throw new Error('duplicate uuid');
          registered.add(sessionId);
          return { dispose: () => registered.delete(sessionId) };
        },
      }),
      ensureChildEntry: async () => '/entry.mjs',
      ensureExplorerAgent: async () => {},
    }
  )(pi);
  const ctx = {
    cwd: process.cwd(),
    isProjectTrusted: () => false,
    sessionManager: { getBranch: () => [], getSessionFile: () => '/session', getSessionId: () => 'uuid' },
  };
  await assert.rejects(events.get('session_start')({}, ctx), /duplicate uuid/);
  assert.equal(registered.size, 0);
  fail = false;
  assert.equal(await events.get('tool_call')({ toolName: 'subagent' }, ctx), undefined);
  assert.equal(registered.size, 2);
  await events.get('session_shutdown')();
  assert.equal(registered.size, 0);
});

test('shutdown during resource preparation cannot publish a late registration', async () => {
  const { pi, events } = harness();
  let release, entered;
  const started = new Promise((resolve) => {
    entered = resolve;
  });
  createSubagentBridgeExtension(
    { agentDir: '/agent', workspaceId: 'w', permissionService: fullPermissions() },
    {
      loadRequiredChildApi: async () => ({
        registerRequiredChildExtensions: () => assert.fail('late registration'),
      }),
      ensureExplorerAgent: async () => {},
      ensureChildEntry: () => {
        entered();
        return new Promise((resolve) => {
          release = resolve;
        });
      },
    }
  )(pi);
  const ctx = {
    cwd: process.cwd(),
    isProjectTrusted: () => false,
    sessionManager: { getBranch: () => [], getSessionFile: () => '/session', getSessionId: () => 'uuid' },
  };
  const startup = events.get('session_start')({}, ctx);
  const rejected = assert.rejects(startup, /closed/);
  await started;
  const shutdown = events.get('session_shutdown')();
  release('/entry.mjs');
  await Promise.all([shutdown, rejected]);
});

test('immutable generated entry loads through Pi and honors parent tool restrictions', async (t) => {
  const admission = await startChildAdmission(async () => true);
  t.after(() => admission.close());
  const descriptor = admission.descriptor('test');
  const root = await mkdtemp(join(tmpdir(), 'octopus-child-load-'));
  const scope = {
    permissions: permissionSnapshot(),
    agentDir: root,
    workspaceId: 'workspace',
    collectionIds: ['one'],
    tools: [...CHILD_TOOLS],
  };
  const path = await ensureChildEntry(scope, descriptor);
  assert.equal(await ensureChildEntry(scope, descriptor), path);
  assert.deepEqual(
    await Promise.all(Array.from({ length: 4 }, () => ensureChildEntry(scope, descriptor))),
    Array(4).fill(path)
  );
  const loader = new DefaultResourceLoader({
    cwd: root,
    agentDir: root,
    settingsManager: SettingsManager.inMemory({ packages: [] }),
    additionalExtensionPaths: [path],
    noExtensions: true,
    noSkills: true,
    noPromptTemplates: true,
    noThemes: true,
  });
  await loader.reload();
  assert.deepEqual(loader.getExtensions().errors, []);
  const extension = loader.getExtensions().extensions.find((item) => item.tools.has('knowledge_search'));
  assert.deepEqual([...extension.tools.keys()].sort(), [...CHILD_TOOLS].sort());
  assert.equal(extension.commands.size, 0);
  const restricted = await ensureChildEntry({ ...scope, tools: [] }, descriptor);
  assert.notEqual(restricted, path);
  const { default: entry } = await import(pathToFileURL(restricted).href);
  const child = harness([]);
  await entry(child.pi);
  assert.equal(child.tools.size, CHILD_TOOLS.length);
  await child.events.get('session_start')();
  assert.deepEqual(child.active, []);
  assert.throws(
    () => child.tools.get('knowledge_search').execute('id', { collectionIds: ['one'], query: 'test' }),
    /CHILD_TOOL_NOT_AUTHORIZED/
  );
  assert.throws(
    () => child.tools.get('memory_read').execute('id', { refs: [] }),
    /CHILD_TOOL_NOT_AUTHORIZED/
  );
  for (const name of ['ocr_image', 'embed_text', 'rerank_documents']) {
    assert.throws(() => child.tools.get(name).execute('id', {}), /CHILD_TOOL_NOT_AUTHORIZED/);
  }
  child.pi.setActiveTools(['knowledge_search', 'ocr_image', 'embed_text', 'rerank_documents']);
  await child.events.get('before_agent_start')();
  assert.deepEqual(child.active, []);
  await child.events.get('session_shutdown')();
  await ensureExplorerAgent(root);
  const agent = join(root, 'agents', 'octopus-explorer.md');
  const expected = await readFile(agent, 'utf8');
  for (const name of CHILD_TOOLS) assert.ok(expected.includes(name));
  await writeFile(agent, 'old managed version');
  await Promise.all(Array.from({ length: 4 }, () => ensureExplorerAgent(root)));
  assert.equal(await readFile(agent, 'utf8'), expected);
});

