/**
 * Record public Pi surfaces and permit lifecycle invocation without a model.
 */
function harness(active = [...CHILD_TOOLS]) {
  const events = new Map(),
    tools = new Map(),
    commands = new Map(),
    messages = [];
  const pi = {
    on: (name, fn) => events.set(name, fn),
    registerTool: (tool) => tools.set(tool.name, tool),
    getActiveTools: () => active,
    setActiveTools: (names) => active.splice(0, active.length, ...names),
    getAllTools: () => CHILD_TOOLS.map((name) => ({ name })),
    registerCommand: (name, definition) => commands.set(name, definition),
    sendMessage: (message) => messages.push(message),
  };
  return { pi, events, tools, active, commands, messages };
}

/**
 * Isolate bridge lifecycle tests from interactive confirmation defaults.
 */
function fullPermissions() {
  const service = createPermissionModeService({ agentDir: join(tmpdir(), 'octopus-test-no-config') });
  service.setMode('full');
  return service;
}

/**
 * Supply the same serialized policy contract generated by a real parent.
 */
function permissionSnapshot(mode = 'full') {
  return { version: 2, cwd: process.cwd(), mode, configuration: loadDefaultPermissionConfiguration() };
}

test('bridge replaces scoped snapshots, serializes refreshes and releases ownership on shutdown', async () => {
  const { pi, events, active } = harness();
  const registry = new Map(),
    scopes = [];
  let session = 'file-a',
    branch = [],
    registrations = 0;
  const ctx = {
    cwd: process.cwd(),
    isProjectTrusted: () => false,
    sessionManager: { getSessionFile: () => session, getSessionId: () => 'uuid', getBranch: () => branch },
  };
  createSubagentBridgeExtension(
    { agentDir: '/agent', workspaceId: 'workspace-a', permissionService: fullPermissions() },
    {
      loadRequiredChildApi: async () => ({
        registerRequiredChildExtensions: ({ sessionId, extensions }) => {
          assert.equal(registry.has(sessionId), false);
          registrations++;
          registry.set(sessionId, extensions);
          return { dispose: () => registry.delete(sessionId) };
        },
      }),
      ensureExplorerAgent: async () => {},
      ensureChildEntry: async (scope) => {
        scopes.push(scope);
        return '/entry.mjs';
      },
    }
  )(pi);
  await events.get('session_start')({}, ctx);
  await Promise.all([
    events.get('tool_call')({ toolName: 'subagent' }, ctx),
    events.get('tool_call')({ toolName: 'subagent' }, ctx),
  ]);
  assert.equal(registrations, 2);
  branch = [
    {
      type: 'custom',
      customType: 'octopus-knowledge-mode',
      data: { version: 1, enabled: true, collectionIds: ['selected'] },
    },
  ];
  await events.get('tool_call')({ toolName: 'subagent' }, ctx);
  assert.deepEqual(scopes.at(-1).collectionIds, ['selected']);
  branch[0].data.enabled = false;
  await events.get('tool_call')({ toolName: 'subagent' }, ctx);
  assert.deepEqual(scopes.at(-1).tools, [
    'ocr_image',
    'embed_text',
    'rerank_documents',
    'memory_recall',
    'memory_read',
  ]);
  active.splice(0, active.length, 'memory_read', 'memory_recall');
  session = 'file-b';
  await events.get('session_start')({}, ctx);
  assert.deepEqual([...registry.keys()], ['file-b', 'uuid']);
  assert.deepEqual(scopes.at(-1).tools, ['memory_recall', 'memory_read']);
  await events.get('session_shutdown')();
  await events.get('session_shutdown')();
  assert.equal(registry.size, 0);
  await events.get('session_start')({}, ctx);
  assert.equal(registry.size, 2);
  branch[0].data = {};
  assert.equal((await events.get('tool_call')({ toolName: 'subagent' }, ctx)).block, true);
  assert.equal(registry.size, 2); // Retained entry enforces admission on slash/API paths too.
  await events.get('session_shutdown')();
});

